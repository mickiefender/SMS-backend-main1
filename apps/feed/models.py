class FeedLesson(models.Model):
    VISIBILITY_CHOICES = (
        ('draft', 'Draft'),
        ('pending_review', 'Pending Review'),
        ('public', 'Public'),
        ('school_only', 'School Only'),
        ('hidden', 'Hidden'),
        ('suspended', 'Suspended'),
    )
    STATUS_CHOICES = (
        ('pending_review', 'Pending Review'),
        ('approved', 'Approved'),
        ('rejected', 'Rejected'),
        ('suspended', 'Suspended'),
    )
    VERIFICATION_CHOICES = (
        ('pending', 'Pending'),
        ('verified', 'Verified'),
        ('rejected', 'Rejected'),
    )

    title = models.CharField(max_length=255)
    description = models.TextField(blank=True)
    topic = models.CharField(max_length=255, blank=True)

    teacher = models.ForeignKey(
        User, on_delete=models.CASCADE, related_name='feed_lessons',
        limit_choices_to={'role': 'teacher'}
    )
    school = models.ForeignKey(
        'schools.School', on_delete=models.SET_NULL, null=True, blank=True,
        related_name='feed_lessons'
    )

    level = models.ForeignKey(
        FeedAcademicLevel, on_delete=models.SET_NULL, null=True, blank=True,
        related_name='lessons'
    )
    class_obj = models.ForeignKey(
        FeedAcademicClass, on_delete=models.SET_NULL, null=True, blank=True,
        related_name='lessons'
    )
    subject = models.ForeignKey(
        FeedSubject, on_delete=models.SET_NULL, null=True, blank=True,
        related_name='lessons'
    )
    tags = models.ManyToManyField(FeedTag, blank=True, related_name='lessons')

    visibility = models.CharField(max_length=20, choices=VISIBILITY_CHOICES, default='public')
    status = models.CharField(max_length=20, choices=STATUS_CHOICES, default='pending_review')
    verification_status = models.CharField(max_length=20, choices=VERIFICATION_CHOICES, default='pending')

    duration_seconds = models.IntegerField(default=0)
    thumbnail_url = models.URLField(max_length=1000, blank=True)
    poster_url = models.URLField(max_length=1000, blank=True)
    extra_metadata = models.JSONField(default=dict, blank=True)

    # ── Cloudflare Stream fields ─────────────────────────────────
    # Replaces the old Supabase video_url / LessonResource-based video.
    # When a video is uploaded to Cloudflare Stream, these fields are populated.
    cloudflare_video_uid = models.CharField(max_length=255, blank=True, db_index=True)
    cloudflare_playback_url = models.URLField(max_length=1000, blank=True)
    cloudflare_thumbnail_url = models.URLField(max_length=1000, blank=True)
    video_duration = models.FloatField(default=0.0)

    # Denormalized counters (maintained by DB triggers)
    view_count = models.BigIntegerField(default=0)
    unique_view_count = models.BigIntegerField(default=0)
    like_count = models.BigIntegerField(default=0)
    save_count = models.BigIntegerField(default=0)
    comment_count = models.BigIntegerField(default=0)
    share_count = models.BigIntegerField(default=0)
    download_count = models.BigIntegerField(default=0)
    completion_rate = models.DecimalField(max_digits=5, decimal_places=2, default=0.00)
    avg_watch_seconds = models.DecimalField(max_digits=10, decimal_places=2, default=0.00)
    trending_score = models.DecimalField(max_digits=12, decimal_places=6, default=0.000000)
    quality_score = models.DecimalField(max_digits=5, decimal_places=2, default=0.00)

    published_at = models.DateTimeField(null=True, blank=True)

    # Read-only generated column maintained by PostgreSQL trigger
    search_vector = SearchVectorField(null=True, editable=False)

    created_at = models.DateTimeField(auto_now_add=True)
    updated_at = models.DateTimeField(auto_now=True)

    class Meta:
        db_table = 'feed_feedlesson'
        ordering = ['-published_at', '-created_at']
        indexes = [
            models.Index(fields=['teacher']),
            models.Index(fields=['school']),
            models.Index(fields=['level']),
            models.Index(fields=['class_obj']),
            models.Index(fields=['subject']),
            models.Index(fields=['visibility', 'status']),
            models.Index(fields=['visibility', 'status', '-published_at']),
            models.Index(fields=['-trending_score', '-published_at']),
            models.Index(fields=['-published_at']),
            models.Index(fields=['-completion_rate']),
            models.Index(fields=['school', 'status', 'visibility']),
            models.Index(fields=['level', 'class_obj', 'subject', 'status', 'visibility']),
            GinIndex(fields=['search_vector']),
            GinIndex(fields=['title'], name='feedlesson_title_gin', opclasses=['gin_trgm_ops']),
            GinIndex(fields=['topic'], name='feedlesson_topic_gin', opclasses=['gin_trgm_ops']),
        ]

    def __str__(self):
        return self.title


