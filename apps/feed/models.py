"""
Alara Learning Feed models.

Design notes:
- All business-critical counters are denormalized onto FeedLesson and kept
  consistent by PostgreSQL triggers (see sql/supabase_feed_schema.sql).
- The `search_vector` field is generated by PostgreSQL and is read-only in
  Django (editable=False). Do not write to it from Python.
- Learning profiles are independent of official academic records.
"""
from django.contrib.postgres.indexes import GinIndex
from django.contrib.postgres.search import SearchVectorField
from django.db import models
from django.conf import settings


User = settings.AUTH_USER_MODEL


